// Demo catalog for a neighbourhood grocery store in Pune. Prices are MRPs in
// rupees (2026), GST follows the GST 2.0 slabs. `pop` is typical units sold per
// day and drives the simulated sales history; `role` drives basket affinities.

export interface CatalogItem {
  name: string;
  brand: string;
  unit: string;
  mrp: number;
  /** Selling price when below MRP. */
  price?: number;
  gst: 0 | 5 | 18 | 40;
  tags: string[];
  pop: number;
  role?: Role;
  /** Shelf life in days for packaged goods (sets an expiry date). */
  life?: number;
  desc?: string;
}

